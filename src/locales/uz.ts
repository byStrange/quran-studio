/**
 * Uzbek (Latin).
 *
 * Latin rather than Cyrillic, which is what the country writes in today; the
 * bundled Al-Mukhtasar tafsir stays Cyrillic because that is how it was
 * published, so the two scripts sit side by side in the reader. That is
 * deliberate — see `lib/i18n.ts`.
 *
 * The apostrophe in oʻ/gʻ is written as the plain ASCII `'` throughout, which
 * is what Uzbek keyboards produce and what every Uzbek reader types; mixing in
 * the typographic ʻ would only make the strings harder to search and edit.
 *
 * Uzbek does not inflect a noun after a numeral — `1 so'z` and `5 so'z` are
 * both correct — so every plural entry repeats one form. The forms are kept
 * rather than collapsed so the shape matches English and a future change stays
 * a one-line edit.
 */
